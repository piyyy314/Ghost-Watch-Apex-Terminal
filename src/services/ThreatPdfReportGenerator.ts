import { jsPDF } from 'jspdf';
import { ThreatEvent, Lure, PacketAnalysisTrace } from '../types';

interface GenerateReportOptions {
  threats: ThreatEvent[];
  lures: Lure[];
  hardwareBoundId?: string;
  analystHandle?: string;
}

export function generateThreatForensicPdfReport({
  threats,
  lures,
  hardwareBoundId = 'HB-9982-AX-2026',
  analystHandle = 'Director P-01 (Apex Operations)'
}: GenerateReportOptions): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;
  let y = margin;

  const activeThreats = threats.filter(t => !t.resolved);
  const resolvedThreats = threats.filter(t => t.resolved);
  const highestCadl = threats.reduce((max, t) => Math.max(max, t.level), 1);

  // Helper to add header on every page
  const drawPageHeader = (pageNum: number) => {
    // Top classification stripe
    doc.setFillColor(15, 23, 42); // slate-900
    doc.rect(0, 0, pageWidth, 12, 'F');
    
    // Top border accent line
    doc.setDrawColor(6, 225, 249); // cyber-cyan
    doc.setLineWidth(0.8);
    doc.line(0, 12, pageWidth, 12);

    doc.setFont('courier', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(6, 225, 249);
    doc.text('CLASSIFIED // GHOST-WATCH APEX SOVEREIGN DEFENSE // CADL FORENSIC REPORT', margin, 8);

    doc.setTextColor(245, 176, 37); // cyber-yellow
    doc.text('LAW ENFORCEMENT & TACTICAL DISCLOSURE', pageWidth - margin - 60, 8);
  };

  // Helper to add footer on every page
  const drawPageFooter = (pageNum: number, totalPages: number) => {
    const footerY = pageHeight - 10;
    doc.setDrawColor(35, 45, 63);
    doc.setLineWidth(0.5);
    doc.line(margin, footerY - 2, pageWidth - margin, footerY - 2);

    doc.setFont('courier', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text(`SECURITY SEAL: SHA-256[${Math.random().toString(36).substring(2, 10).toUpperCase()}-APEX]`, margin, footerY + 2);
    doc.text(`HW-BOUND: ${hardwareBoundId}`, margin + 65, footerY + 2);
    doc.text(`PAGE ${pageNum} OF ${totalPages}`, pageWidth - margin - 22, footerY + 2);
  };

  // First page header
  drawPageHeader(1);
  y = 20;

  // Title block
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42);
  doc.text('ATTRIBUTION DATABASE (ADB) THREAT AUDIT', margin, y);
  y += 6;

  doc.setFont('courier', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(2, 132, 199);
  doc.text('GHOST-WATCH ADVANCED CANARY TRAP & REAL-TIME INCIDENT DISCLOSURE', margin, y);
  y += 7;

  // Metadata Card
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.4);
  doc.roundedRect(margin, y, pageWidth - (margin * 2), 26, 2, 2, 'FD');

  const metaY = y + 5;
  doc.setFont('courier', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(71, 85, 105);

  const col1X = margin + 4;
  const col2X = margin + 64;
  const col3X = margin + 128;

  doc.text(`Report Timestamp: ${new Date().toISOString().replace('T', ' ').substring(0, 19)} UTC`, col1X, metaY);
  doc.text(`Generated By: ${analystHandle}`, col1X, metaY + 5);
  doc.text(`Hardware Anchor: ${hardwareBoundId}`, col1X, metaY + 10);
  doc.text(`FIPS-203 PQC Status: ML-KEM-768 VALIDATED`, col1X, metaY + 15);

  doc.text(`Total Incidents Logged: ${threats.length}`, col2X, metaY);
  doc.text(`Active Breaches (Pending): ${activeThreats.length}`, col2X, metaY + 5);
  doc.text(`Contained / Cleared: ${resolvedThreats.length}`, col2X, metaY + 10);
  doc.text(`Canary Traps Deployed: ${lures.length}`, col2X, metaY + 15);

  doc.setFont('courier', 'bold');
  doc.setTextColor(220, 38, 38);
  doc.text(`CADL Max Level: LEVEL ${highestCadl}`, col3X, metaY);
  doc.setTextColor(71, 85, 105);
  doc.setFont('courier', 'normal');
  doc.text(`Mesh Mask Ratio: 99.8% (Lazarus)`, col3X, metaY + 5);
  doc.text(`LoRa OOB Spectrum: 915.0 MHz`, col3X, metaY + 10);
  doc.text(`Confidentiality Tier: SOVEREIGN-RESTRICTED`, col3X, metaY + 15);

  y += 32;

  // Executive Summary Section
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('1. EXECUTIVE THREAT INCIDENT ROSTER', margin, y);
  y += 5;

  // Table header
  const tableX = margin;
  const tableWidth = pageWidth - (margin * 2);
  const rowHeight = 7;

  doc.setFillColor(30, 41, 59);
  doc.rect(tableX, y, tableWidth, rowHeight, 'F');

  doc.setFont('courier', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(255, 255, 255);
  doc.text('INCIDENT ID', tableX + 2, y + 4.8);
  doc.text('TIMESTAMP', tableX + 26, y + 4.8);
  doc.text('CADL', tableX + 66, y + 4.8);
  doc.text('SOURCE IP / ADVERSARY NODE', tableX + 80, y + 4.8);
  doc.text('ACTION TAKEN', tableX + 138, y + 4.8);
  doc.text('STATUS', tableX + 168, y + 4.8);
  y += rowHeight;

  // Table rows
  threats.forEach((threat, idx) => {
    if (y > pageHeight - 35) {
      doc.addPage();
      drawPageHeader(doc.getNumberOfPages());
      y = 20;

      // Repeat table header
      doc.setFillColor(30, 41, 59);
      doc.rect(tableX, y, tableWidth, rowHeight, 'F');
      doc.setFont('courier', 'bold');
      doc.setFontSize(7.5);
      doc.setTextColor(255, 255, 255);
      doc.text('INCIDENT ID', tableX + 2, y + 4.8);
      doc.text('TIMESTAMP', tableX + 26, y + 4.8);
      doc.text('CADL', tableX + 66, y + 4.8);
      doc.text('SOURCE IP / ADVERSARY NODE', tableX + 80, y + 4.8);
      doc.text('ACTION TAKEN', tableX + 138, y + 4.8);
      doc.text('STATUS', tableX + 168, y + 4.8);
      y += rowHeight;
    }

    const isEven = idx % 2 === 0;
    doc.setFillColor(isEven ? 255 : 248, isEven ? 255 : 250, isEven ? 255 : 252);
    doc.rect(tableX, y, tableWidth, rowHeight, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.line(tableX, y + rowHeight, tableX + tableWidth, y + rowHeight);

    doc.setFont('courier', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(2, 132, 199);
    doc.text(threat.id, tableX + 2, y + 4.6);

    doc.setFont('courier', 'normal');
    doc.setTextColor(51, 65, 85);
    const timeStr = threat.timestamp.replace('T', ' ').substring(0, 16);
    doc.text(timeStr, tableX + 26, y + 4.6);

    // CADL badge
    if (threat.level >= 3) {
      doc.setTextColor(220, 38, 38);
      doc.setFont('courier', 'bold');
    } else {
      doc.setTextColor(217, 119, 6);
      doc.setFont('courier', 'normal');
    }
    doc.text(`LVL ${threat.level}`, tableX + 66, y + 4.6);

    // Source IP & node
    doc.setTextColor(30, 41, 59);
    doc.setFont('courier', 'normal');
    const nodeTruncated = threat.sourceNode.length > 22 ? `${threat.sourceNode.substring(0, 20)}...` : threat.sourceNode;
    doc.text(`${threat.sourceIp} (${nodeTruncated})`, tableX + 80, y + 4.6);

    // Action taken
    const actionTruncated = threat.actionTaken.length > 18 ? `${threat.actionTaken.substring(0, 16)}...` : threat.actionTaken;
    doc.text(actionTruncated, tableX + 138, y + 4.6);

    // Status
    if (threat.resolved) {
      doc.setTextColor(22, 163, 74);
      doc.text('CONTAINED', tableX + 168, y + 4.6);
    } else {
      doc.setTextColor(220, 38, 38);
      doc.setFont('courier', 'bold');
      doc.text('ACTIVE BREACH', tableX + 168, y + 4.6);
    }

    y += rowHeight;
  });

  y += 8;

  // Deep-dive forensic section for all incidents
  if (y > pageHeight - 65) {
    doc.addPage();
    drawPageHeader(doc.getNumberOfPages());
    y = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('2. FORENSIC INCIDENT DISSECTION & PACKET TELEMETRY', margin, y);
  y += 6;

  threats.forEach((threat, idx) => {
    const trace = threat.packetTrace;

    // Check if enough room for threat card
    if (y > pageHeight - 55) {
      doc.addPage();
      drawPageHeader(doc.getNumberOfPages());
      y = 20;
    }

    // Threat Card Container
    const cardHeight = trace ? 48 : 28;
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(203, 213, 225);
    doc.roundedRect(margin, y, pageWidth - (margin * 2), cardHeight, 1.5, 1.5, 'FD');

    // Incident top ribbon
    doc.setFillColor(threat.level >= 3 ? 239 : 241, threat.level >= 3 ? 68 : 245, threat.level >= 3 ? 68 : 249);
    doc.roundedRect(margin, y, 4, cardHeight, 1.5, 1.5, 'F');

    const cardContentX = margin + 7;
    let cardY = y + 5;

    doc.setFont('courier', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(15, 23, 42);
    doc.text(`INCIDENT ${threat.id} — ${threat.actionTaken} [CADL LEVEL ${threat.level}]`, cardContentX, cardY);

    doc.setFont('courier', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(`Timestamp: ${threat.timestamp} | Source: ${threat.sourceIp} (${threat.sourceNode})`, cardContentX, cardY + 4.5);

    doc.setTextColor(51, 65, 85);
    const detailsLines = doc.splitTextToSize(`Details: ${threat.details}`, pageWidth - (margin * 2) - 12);
    doc.text(detailsLines, cardContentX, cardY + 9);

    if (trace) {
      cardY += 15;
      doc.setDrawColor(226, 232, 240);
      doc.line(cardContentX, cardY, pageWidth - margin - 4, cardY);
      cardY += 4;

      doc.setFont('courier', 'bold');
      doc.setFontSize(7);
      doc.setTextColor(2, 132, 199);
      doc.text(`PACKET TRACE: ${trace.captureId} [${trace.header.protocol}]`, cardContentX, cardY);

      doc.setFont('courier', 'normal');
      doc.setTextColor(71, 85, 105);
      doc.text(`Flow: ${trace.header.srcIp}:${trace.header.srcPort} -> ${trace.header.dstIp}:${trace.header.dstPort} | TTL: ${trace.header.ttl} | Frame: ${trace.header.frameLengthBytes} bytes`, cardContentX, cardY + 3.8);

      doc.text(`MITRE ATT&CK: ${trace.payload.mitreAttackTactic} (${trace.payload.mitreTechniqueId}) | Entropy: ${trace.payload.payloadEntropy} bits/byte | Threat Score: ${trace.payload.heuristicThreatScore}/100`, cardContentX, cardY + 7.6);

      doc.setTextColor(180, 83, 9);
      doc.text(`Snort Sig: ${trace.snortRuleSignature.substring(0, 90)}...`, cardContentX, cardY + 11.4);

      doc.setTextColor(15, 23, 42);
      doc.setFont('courier', 'bold');
      doc.text(`Containment Directive: ${trace.containmentRecommendation}`, cardContentX, cardY + 15.2);
    }

    y += cardHeight + 5;
  });

  // 3. Canary Traps Roster
  if (y > pageHeight - 50) {
    doc.addPage();
    drawPageHeader(doc.getNumberOfPages());
    y = 20;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('3. CANARY TRAP DEPLOYMENT INVENTORY', margin, y);
  y += 5;

  lures.forEach((lure) => {
    if (y > pageHeight - 25) {
      doc.addPage();
      drawPageHeader(doc.getNumberOfPages());
      y = 20;
    }

    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(203, 213, 225);
    doc.roundedRect(margin, y, pageWidth - (margin * 2), 14, 1, 1, 'FD');

    doc.setFont('courier', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(2, 132, 199);
    doc.text(`LURE: ${lure.id}`, margin + 4, y + 4.5);

    doc.setFont('courier', 'normal');
    doc.setTextColor(71, 85, 105);
    doc.text(`Target Node: ${lure.targetNode} | Document: ${lure.documentType} | Watermark: ${lure.watermarkType}`, margin + 4, y + 8.5);
    doc.text(`DNS Canary Token: ${lure.dnsToken} | Status: ${lure.isTriggered ? 'TRIGGERED / COMPROMISED' : 'LISTENING'} | Hits: ${lure.triggerCount}`, margin + 4, y + 12);

    y += 17;
  });

  // Stamp total pages and footers across all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    drawPageFooter(i, totalPages);
  }

  return doc;
}
